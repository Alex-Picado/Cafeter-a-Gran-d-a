    /**
     * Carga todos los clientes en la tabla desde el archivo .txt
     */
    private void cargarClientes() {
        DefaultTableModel model = (DefaultTableModel) clientesTable.getModel();
        model.setRowCount(0);
        
        Collection<Cliente> clientes = clienteController.obtenerTodosLosClientes();
        
        for (Cliente cliente : clientes) {
            Object[] fila = {
                cliente.getId(),
                cliente.getNombre(),
                cliente.getTelefono(),
                cliente.getCorreo(),
                cliente.getDireccion(),
                cliente.getFrecuencia()
            };
            model.addRow(fila);
        }
    }
    
    /**
     * Agrega un listener de búsqueda en tiempo real al campo de texto.
     */
    private void agregarFiltro() {
        buscarTextField.getDocument().addDocumentListener(new DocumentListener() {
            public void insertUpdate(DocumentEvent e) {
                filtrarTabla();
            }
            public void removeUpdate(DocumentEvent e) {
                filtrarTabla();
            }
            public void changedUpdate(DocumentEvent e) {
                filtrarTabla();
            }
        });
    }
    
    /**
     * Filtra la tabla según el texto de búsqueda ingresado.
     */
    private void filtrarTabla() {
        String textoBusqueda = buscarTextField.getText().toLowerCase();
        
        DefaultTableModel model = (DefaultTableModel) clientesTable.getModel();
        model.setRowCount(0);
        
        Collection<Cliente> clientes = clienteController.obtenerTodosLosClientes();
        
        for (Cliente cliente : clientes) {
            if (cliente.getId().toLowerCase().contains(textoBusqueda) ||
                cliente.getNombre().toLowerCase().contains(textoBusqueda) ||
                cliente.getTelefono().toLowerCase().contains(textoBusqueda) ||
                cliente.getCorreo().toLowerCase().contains(textoBusqueda) ||
                cliente.getDireccion().toLowerCase().contains(textoBusqueda)) {
                
                Object[] fila = {
                    cliente.getId(),
                    cliente.getNombre(),
                    cliente.getTelefono(),
                    cliente.getCorreo(),
                    cliente.getDireccion(),
                    cliente.getFrecuencia()
                };
                model.addRow(fila);
            }
        }
    }

