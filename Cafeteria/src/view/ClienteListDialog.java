    private void btnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSeleccionarActionPerformed
        int selectedRow = clientesTable.getSelectedRow();
        
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Seleccione un cliente de la lista.",
                    "Advertencia",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String clienteId = (String) clientesTable.getValueAt(selectedRow, 0);
        Cliente clienteSeleccionado = clienteController.buscarCliente(clienteId);
        
        if (clienteSeleccionado != null && panelGestionarClientes != null) {
            panelGestionarClientes.pobllarFormularioConCliente(clienteSeleccionado);
        }
        
        this.dispose();
    }//GEN-LAST:event_btnSeleccionarActionPerformed

